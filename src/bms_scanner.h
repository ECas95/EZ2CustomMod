struct CustomBmsSong {
    std::string id;
    std::string mode;        // internal mode name, e.g. 5keyMix
    std::string modeFolder;  // folder name under BMSData, e.g. 5KeyMix
    std::string category;
    std::string songDir;
    std::string cacheDir;
    std::string title;
    std::string artist;
    // Shared with this song's virtual copies -- identical across the whole group, so it is stored
    // once. Write only through .mut(), and only during the scan.
    SharedVec<std::string> charts;
    SharedVec<CustomBmsChart> chartMeta;
    SharedVec<std::string> audioFiles;
    SharedVec<std::string> imageFiles;
    SharedVec<std::string> videoFiles;

    // Virtual copies generated from a source-mode chart. The original BMS files are
    // never rewritten; the direct loader performs the mode conversion in memory.
    bool autoGenerated = false;
    std::string sourceMode;

    // Virtual song.bin-compatible difficulty/BPM fields.
    // Slots map to FNEX song.bin record blocks: NM, HD, SHD/MX, EX.
    int levelNM = 0;
    int levelHD = 0;
    int levelSHD = 0;
    int levelEX = 0;
    // The fifth chart, shown in the wheel's dormant leftmost column (see the EZ notes in
    // trace_hooks/mod_main): the easiest chart of a song that ships five or more.
    int levelEZ = 0;
    float bpmNM = 0.0f;
    float bpmHD = 0.0f;
    float bpmSHD = 0.0f;
    float bpmEX = 0.0f;
    float bpmEZ = 0.0f;
};

