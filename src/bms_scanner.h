// Autogen makes one virtual copy of every song per target mode -- 8 copies for every original at the
// current mode list. A plain deep copy duplicates the whole payload each time, and chartMeta alone is
// 61% of a song's heap, so the catalog cost scaled with modes x songs for data that is byte-identical
// across the group. SharedVec holds the buffer behind a shared_ptr so a copy shares it instead.
//
// Reads mirror std::vector so existing call sites are unchanged; MUTATION is only reachable through
// mut(), which makes every writer visible to the compiler. That matters: every writer must run during
// the scan, BEFORE ExpandAutoGeneratedModes hands the buffer to the copies -- a write afterwards would
// silently rewrite the original and all its siblings.
template <typename T>
class SharedVec {
public:
    typedef typename std::vector<T>::const_iterator const_iterator;
    size_t size() const { return p_ ? p_->size() : 0; }
    bool empty() const { return !p_ || p_->empty(); }
    const T& operator[](size_t i) const { return (*p_)[i]; }
    const T& front() const { return p_->front(); }
    const_iterator begin() const { return get().begin(); }
    const_iterator end() const { return get().end(); }
    const std::vector<T>& get() const {
        static const std::vector<T> kEmpty;
        return p_ ? *p_ : kEmpty;
    }
    operator const std::vector<T>&() const { return get(); }
    std::vector<T>& mut() {
        if (!p_) p_.reset(new std::vector<T>());
        return *p_;
    }
    void push_back(const T& v) { mut().push_back(v); }
private:
    std::shared_ptr<std::vector<T> > p_;
};

// What the chart's own notes say about it, measured once at scan time and cached.
//
// #PLAYLEVEL alone does not rank a library. Measured over 1379 charts: the declared level tracks
// the note data well up to 17 and then collapses -- 46% of songs declare 18 for their hardest
// chart, and inside level 18 the peak density runs from 13 to 83 notes a second. These are the
// numbers that do separate them, and they are what the rating below is built from.
static const int kDensityBuckets = 64;   // one bar of the song-select graph each

struct ChartStats {
    uint32_t notes = 0;         // playable notes (long notes count once)
    float    seconds = 0.0f;    // first note to last
    float    nps = 0.0f;        // notes per second across that span
    float    peakNps = 0.0f;    // busiest 2-second window
    float    chordPct = 0.0f;   // notes sharing a timestamp with another
    float    jackPct = 0.0f;    // notes repeating a lane within 150 ms
    int      rated = 0;         // 1..20 derived from the above; 0 = not measured
    // The chart's shape over time: the span split into equal slices, each scaled 0..255 against
    // the busiest one. What the song-select graph draws, and the reason it is stored rather than
    // recomputed -- the notes are only in hand while the file is being read at scan time.
    unsigned char density[kDensityBuckets] = {};
    bool measured() const { return notes > 0 && seconds > 0.0f; }
};

