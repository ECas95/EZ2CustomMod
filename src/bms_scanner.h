// Autogen makes one virtual copy of every song per target mode -- 8 copies for every original at the
// current mode list. A plain deep copy duplicates the whole payload each time, and chartMeta alone is
// 61% of a song's heap, so the catalog cost scaled with modes x songs for data that is byte-identical
// across the group. SharedVec holds the buffer behind a shared_ptr so a copy shares it instead.
//
// Reads mirror std::vector so existing call sites are unchanged; MUTATION is only reachable through
// mut(), which makes every writer visible to the compiler. That matters: every writer must run during
// the scan, BEFORE ExpandAutoGeneratedModes hands the buffer to the copies -- a write afterwards would
// silently rewrite the original and all its siblings.
template <typename T>
class SharedVec {
public:
    typedef typename std::vector<T>::const_iterator const_iterator;
    size_t size() const { return p_ ? p_->size() : 0; }
    bool empty() const { return !p_ || p_->empty(); }
    const T& operator[](size_t i) const { return (*p_)[i]; }
    const T& front() const { return p_->front(); }
    const_iterator begin() const { return get().begin(); }
    const_iterator end() const { return get().end(); }
    const std::vector<T>& get() const {
        static const std::vector<T> kEmpty;
        return p_ ? *p_ : kEmpty;
    }
    operator const std::vector<T>&() const { return get(); }
    std::vector<T>& mut() {
        if (!p_) p_.reset(new std::vector<T>());
        return *p_;
    }
    void push_back(const T& v) { mut().push_back(v); }
private:
    std::shared_ptr<std::vector<T> > p_;
};

struct CustomBmsChart {
    std::string file;
    std::string title;
    std::string artist;
    std::string stageFile;
    std::string banner;
    std::string bpm;
    std::string playLevel;
    std::string difficulty;
    int slot = -1;
    std::vector<std::string> wavRefs;
    std::vector<std::string> bmpRefs;
};

struct CustomBmsSong {
    std::string id;
    std::string mode;        // internal mode name, e.g. 5keyMix
    std::string modeFolder;  // folder name under BMSData, e.g. 5KeyMix
    std::string category;
    std::string songDir;
    std::string cacheDir;
    std::string title;
    std::string artist;
    // Shared with this song's virtual copies -- identical across the whole group, so it is stored
    // once. Write only through .mut(), and only during the scan.
    SharedVec<std::string> charts;
    SharedVec<CustomBmsChart> chartMeta;
    SharedVec<std::string> audioFiles;
    SharedVec<std::string> imageFiles;
    SharedVec<std::string> videoFiles;

    // Virtual copies generated from a source-mode chart. The original BMS files are
    // never rewritten; the direct loader performs the mode conversion in memory.
    bool autoGenerated = false;
    std::string sourceMode;

    // Virtual song.bin-compatible difficulty/BPM fields.
    // Slots map to FNEX song.bin record blocks: NM, HD, SHD/MX, EX.
    int levelNM = 0;
    int levelHD = 0;
    int levelSHD = 0;
    int levelEX = 0;
    float bpmNM = 0.0f;
    float bpmHD = 0.0f;
    float bpmSHD = 0.0f;
    float bpmEX = 0.0f;
};

