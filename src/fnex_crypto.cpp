static const unsigned char* selectKey(FnexCryptoKind kind) {
    switch (kind) {
        case FnexCryptoKind::Ini: return kFnexIniKey;
        case FnexCryptoKind::Ez:  return kFnexEzKey;
        case FnexCryptoKind::Ezi: return kFnexEziKey;
    }
    return kFnexEziKey;
}

const char* FnexCryptoKindName(FnexCryptoKind kind) {
    switch (kind) {
        case FnexCryptoKind::Ini: return "ini";
        case FnexCryptoKind::Ez:  return "ez";
        case FnexCryptoKind::Ezi: return "ezi";
    }
    return "unknown";
}

std::vector<unsigned char> FnexEncryptBuffer(const unsigned char* data, size_t size, FnexCryptoKind kind) {
    const unsigned char* key = selectKey(kind);
    std::vector<unsigned char> tmp(size, 0);
    if (!data || size == 0) return tmp;

    size_t off = 0;
    int keyIndex = 0;
    bool wideBlock = false;
    while (off < size) {
        size_t len = 0;
        if (size < off + 8) {
            len = size - off;
        } else {
            if (wideBlock) {
                len = 16;
                if (size < off + 16) len = size - off;
            } else {
                len = 8;
            }
            wideBlock = !wideBlock;
        }
        for (size_t u = 0; u < len; ++u) {
            int k = keyIndex + static_cast<int>(len) - static_cast<int>(u) - 1;
            if (k > 0x1ff) k -= 0x200;
            unsigned char add = key[k & 0x1ff];
            tmp[off + len - 1 - u] = static_cast<unsigned char>((data[off + u] + add) & 0xff);
        }
        keyIndex += static_cast<int>(len);
        if (keyIndex > 0x1ff) keyIndex -= 0x200;
        if (len > 8) off = (off - 8) + len;
        off += 8;
    }
    std::reverse(tmp.begin(), tmp.end());
    return tmp;
}

std::vector<unsigned char> FnexEncryptString(const std::string& text, FnexCryptoKind kind) {
    return FnexEncryptBuffer(reinterpret_cast<const unsigned char*>(text.data()), text.size(), kind);
}

bool FnexWriteEncryptedFile(const std::string& path, const unsigned char* data, size_t size, FnexCryptoKind kind) {
    std::vector<unsigned char> enc = FnexEncryptBuffer(data, size, kind);
    FILE* f = std::fopen(path.c_str(), "wb");
    if (!f) return false;
    if (!enc.empty()) std::fwrite(enc.data(), 1, enc.size(), f);
    std::fclose(f);
    return true;
}

bool FnexWriteEncryptedTextFile(const std::string& path, const std::string& text, FnexCryptoKind kind) {
    return FnexWriteEncryptedFile(path, reinterpret_cast<const unsigned char*>(text.data()), text.size(), kind);
}
